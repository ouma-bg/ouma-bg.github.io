const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const logoDirectory = path.join(__dirname, 'assets', 'skill-logos');
const brandColors = {pydantic:'#E92063',n8n:'#EA4B71',googlecolab:'#F9AB00'};
const logos = {};
for (const name of fs.readdirSync(logoDirectory).filter(n => n.endsWith('.svg'))) {
  let svg = fs.readFileSync(path.join(logoDirectory,name),'utf8');
  if (!svg.includes('<svg') || !svg.includes('</svg>')) throw new Error('Invalid SVG: '+name);
  svg = svg.replace(/<\?xml[^>]*\?>/g,'').replace(/<!DOCTYPE[\s\S]*?>/g,'');
  svg = svg.replace(/<svg\b/, '<svg aria-hidden="true" focusable="false"');
  const brand = name.split('-')[0];
  if (brandColors[brand]) svg = svg.replace('<svg ', `<svg fill="${brandColors[brand]}" `);
  logos[name] = svg;
}
const dataSource = fs.readFileSync('skills.js','utf8').split('const skillGlyphs')[0];
const context = {};
vm.runInNewContext(dataSource+';this.groups=skillGroups;this.logos=skillLogos;',context);
for(const logo of Object.values(context.logos)) {
 const name = `${logo}-${logo}-${logo==='amazonwebservices'?'original-wordmark':'original'}.svg`;
 if (!logos[name]) throw new Error('Missing local logo: '+name);
}
const count = context.groups.reduce((n,g)=>n+g.items.length+g.training.length,0);
if(count!==106) throw new Error('Expected 106 skills, found '+count);
fs.writeFileSync('skill-logos.js','// Generated by build.cjs from local SVG assets.\nconst localSkillLogos = '+JSON.stringify(logos)+';\n');
const projectContext={};vm.runInNewContext(fs.readFileSync('projects-data.js','utf8')+';this.projects=portfolioProjects;',projectContext);
if(projectContext.projects.length!==11)throw new Error('Expected 11 projects');
for(const project of projectContext.projects){const filename=path.join(__dirname,project.image);if(!fs.existsSync(filename))throw new Error('Missing cover: '+project.image);const bytes=fs.readFileSync(filename);if(bytes.subarray(1,4).toString()!=='PNG')throw new Error('Invalid PNG: '+project.image);}
const skillsContext={};vm.runInNewContext(fs.readFileSync('skills-data.js','utf8')+';this.skills=portfolioSkills;',skillsContext);const uniqueNames=new Set(context.groups.flatMap(g=>[...g.items,...g.training]));if(skillsContext.skills.length!==uniqueNames.size||skillsContext.skills.some(s=>!uniqueNames.has(s.name)))throw new Error('Skills lost or duplicated');
const badgesContext={};vm.runInNewContext(fs.readFileSync('certifications-data.js','utf8')+';this.badges=portfolioBadges;',badgesContext);if(badgesContext.badges.length!==7)throw new Error('Expected seven badges');for(const badge of badgesContext.badges){if(!fs.existsSync(badge.image))throw new Error('Missing badge image');if(!/^https:\/\/www.credly.com\/badges\/[a-f0-9-]+$/.test(badge.link))throw new Error('Invalid Credly badge link');}
const output = path.join(__dirname,'dist');
fs.mkdirSync(output,{recursive:true});
for(const file of ['i18n.js','config.js','theme.js','index.html','home.css','home-components.js','skills.js','skills-data.js','skill-logos.js','projects-data.js','projects.js','certifications-data.js','certifications.js','experiences-data.js','experiences.js','contact.js']) fs.copyFileSync(file,path.join(output,file));
fs.cpSync('locales',path.join(output,'locales'),{recursive:true});
// Publish runtime assets only, not screenshots, old CVs or working documents.
fs.mkdirSync(path.join(output,'assets'),{recursive:true});
for(const directory of ['badges','companies','project-covers','skill-logos']) {
 fs.cpSync(path.join('assets',directory),path.join(output,'assets',directory),{recursive:true});
}
for(const asset of ['oumaima-haute-resolution.png','oumaima-original.png','ensa-original.png','portfolio-inter.woff2','material-design.svg','CV_Oumaima_Baghadi.pdf','QR_Portfolio_Oumaima_Baghadi.svg','QR_Portfolio_Oumaima_Baghadi.png']) {
 fs.copyFileSync(path.join('assets',asset),path.join(output,'assets',asset));
}
const configContext={};vm.runInNewContext(fs.readFileSync('config.js','utf8')+';this.config=portfolioConfig;',configContext);
if(!fs.readFileSync(path.join(output,configContext.config.cvPath)).subarray(0,5).equals(Buffer.from('%PDF-')))throw new Error('Invalid CV PDF');
if(projectContext.projects.some(project=>!/^https:\/\/lnkd\.in\/p\//.test(project.linkedinPostUrl)))throw new Error('Missing LinkedIn demonstration');
fs.writeFileSync(path.join(output,'.nojekyll'),'');
console.log(`Build statique réussi : ${Object.keys(context.logos).length} associations de logos vérifiées, ${count} compétences, sortie dist/`);

